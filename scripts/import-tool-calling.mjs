import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { parse } from 'acorn';

const { values } = parseArgs({ options: { 'upstream-dir': { type: 'string' }, write: { type: 'boolean' } } });
const commit = '7e8663cd9c184a550b37238218bdd32c6efc68e9';
const upstreamPath = 'public/scripts/tool-calling.js';
const source = readFileSync(resolve(values['upstream-dir'] ?? `.cache/research/SillyTavern-${commit}`, upstreamPath), 'utf8');
const hash = value => createHash('sha256').update(value).digest('hex');
const upstreamSha256 = '934be74f6bd672a821e5f3e5dc34ad4548c1cac60ee41c48feaa630e6e2f7712';
if (hash(source) !== upstreamSha256) throw new Error('ToolManager input differs from the fixed upstream');
const ast = parse(source, { ecmaVersion: 'latest', sourceType: 'module' });
if (!ast.body.some(node => node.type === 'ExportNamedDeclaration' && node.declaration?.id?.name === 'ToolManager'))
  throw new Error('Fixed upstream is missing ToolManager');
// This is one unchanged browser module, not the upstream application. Its
// existing imports resolve to our independently implemented host adapters.
const output = '// SPDX-License-Identifier: AGPL-3.0-only\n'
  + `// Copyright SillyTavern contributors; ${commit}, ${upstreamPath}.\n`
  + '// Generated by scripts/import-tool-calling.mjs. Do not edit the embedded module.\n'
  + `export const toolCallingRuntimeSource = ${JSON.stringify(source)};\n`;
const path = 'apps/local-service/src/tool-calling-upstream.ts';
const manifest = { repository: 'https://github.com/SillyTavern/SillyTavern', commit, license: 'AGPL-3.0-only', files: [{
  path: 'src/tool-calling-upstream.ts', upstreamPath, upstreamSha256, adaptedSha256: hash(output),
  components: ['ToolDefinition', 'ToolManager', 'ToolManager.initToolSlashCommands'],
  adaptation: 'Unchanged complete tool-calling browser module. Original imports bind to independent host APIs; request/effect/continuation adapters live separately in project-authored modules. No upstream server or application is included.',
}] };
const manifestPath = 'apps/local-service/tool-calling-upstream.json';
if (values.write) {
  writeFileSync(path, output); writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
} else {
  if (readFileSync(path, 'utf8') !== output || JSON.stringify(JSON.parse(readFileSync(manifestPath, 'utf8'))) !== JSON.stringify(manifest))
    throw new Error('ToolManager output/provenance differs; regenerate with --write');
}
console.log('Verified fixed ToolManager module: ' + hash(output));
